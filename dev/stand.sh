#!/usr/bin/env bash
#
# Local development stand: Moodle + ONLYOFFICE Docs with this plugin mounted into Moodle,
# plus moodle-assignsubmission_onlyoffice when a checkout of it is found (ASSIGNSUBMISSION_DIR).
# Usage: dev/stand.sh [up|down|destroy|grunt [assign]|upgrade|php <script> [args]|shell|logs [service]]

set -euo pipefail
# Git Bash would otherwise rewrite container paths such as /var/www/html into Windows paths.
export MSYS_NO_PATHCONV=1

DEV_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$DEV_DIR"

if [ -f .env ]; then
    set -a
    . ./.env
    set +a
fi

export MOODLE_BRANCH="${MOODLE_BRANCH:-MOODLE_503_STABLE}"
export MOODLE_PORT="${MOODLE_PORT:-8000}"
export DS_PORT="${DS_PORT:-8080}"
export DS_JWT_SECRET="${DS_JWT_SECRET:-secret}"
ADMIN_USER="${ADMIN_USER:-admin}"
ADMIN_PASS="${ADMIN_PASS:-admin}"
# Relative to dev/; set it empty in .env to leave the subplugin out.
export ASSIGNSUBMISSION_DIR="${ASSIGNSUBMISSION_DIR-../../moodle-assignsubmission_onlyoffice}"

with_assignsubmission() {
    [ -n "$ASSIGNSUBMISSION_DIR" ] && [ -f "$ASSIGNSUBMISSION_DIR/version.php" ]
}

compose() {
    if with_assignsubmission; then
        docker compose -f docker-compose.yml -f docker-compose.assignsubmission.yml "$@"
    else
        docker compose "$@"
    fi
}

log() {
    printf '\033[1;34m==>\033[0m %s\n' "$*"
}

moodle_cloned() {
    compose run --rm --no-deps -T --entrypoint test git -d /git/.git
}

# Moodle 5.1+ serves from public/ and keeps plugins there; 4.5 has everything in the root.
detect_layout() {
    if compose run --rm --no-deps -T --entrypoint test git -d /git/public; then
        export MOODLE_MOD_DIR=public/mod
        export APACHE_DOCUMENT_ROOT=/var/www/html/public
    else
        export MOODLE_MOD_DIR=mod
        export APACHE_DOCUMENT_ROOT=/var/www/html
    fi
}

write_config() {
    compose run --rm --no-deps -T --entrypoint sh git -c 'cat > /git/config.php' <<PHP
<?php
// Generated by dev/stand.sh on every start; edits are overwritten.
unset(\$CFG);
global \$CFG;
\$CFG = new stdClass();

\$CFG->dbtype    = 'pgsql';
\$CFG->dblibrary = 'native';
\$CFG->dbhost    = 'db';
\$CFG->dbname    = 'moodle';
\$CFG->dbuser    = 'moodle';
\$CFG->dbpass    = 'moodle';
\$CFG->prefix    = 'm_';

// Document Server reaches Moodle as http://webserver; without this Moodle would redirect it to localhost.
\$CFG->wwwroot = ((\$_SERVER['HTTP_HOST'] ?? '') === 'webserver') ? 'http://webserver' : 'http://localhost:${MOODLE_PORT}';
\$CFG->dataroot = '/var/www/moodledata';
\$CFG->admin = 'admin';
\$CFG->directorypermissions = 02777;

// Docker addresses are private and DS_PORT is non-standard, both of which Moodle's curl blocks by default.
\$CFG->curlsecurityblockedhosts = '';
\$CFG->curlsecurityallowedport = '';

\$CFG->debug = E_ALL;
\$CFG->debugdisplay = 1;
\$CFG->cachejs = false;
\$CFG->cachetemplates = false;
\$CFG->langstringcache = false;
\$CFG->noemailever = true;

require_once(__DIR__ . '/lib/setup.php');
PHP
}

moodle_php() {
    compose exec -T --user www-data webserver php "$@"
}

is_installed() {
    [ "$(compose exec -T db psql -U moodle -d moodle -tAc "SELECT to_regclass('m_config') IS NOT NULL")" = "t" ]
}

set_plugin_config() {
    moodle_php admin/cli/cfg.php --component=onlyofficeeditor --name="$1" --set="$2"
}

cmd_up() {
    if [ -z "$(ls -A ../newdocs 2>/dev/null)" ]; then
        log "Initialising the newdocs submodule"
        git -C .. submodule update --init --recursive
    fi

    if ! moodle_cloned; then
        log "Cloning Moodle $MOODLE_BRANCH"
        compose run --rm --no-deps -T git clone --depth 1 --branch "$MOODLE_BRANCH" https://github.com/moodle/moodle.git .
    fi
    detect_layout
    write_config

    log "Starting containers (Document Server takes a minute or two on first start)"
    compose up -d --wait db webserver ds-proxy documentserver
    compose exec -T webserver chown www-data:www-data /var/www/moodledata

    if is_installed; then
        log "Upgrading Moodle"
        moodle_php admin/cli/upgrade.php --non-interactive
    else
        log "Installing Moodle"
        moodle_php admin/cli/install_database.php --agree-license \
            --fullname="ONLYOFFICE dev" --shortname="oodev" --summary="" \
            --adminuser="$ADMIN_USER" --adminpass="$ADMIN_PASS" --adminemail="admin@example.com"
    fi

    log "Configuring the ONLYOFFICE plugin"
    set_plugin_config documentserverurl "http://localhost:$DS_PORT"
    set_plugin_config documentserverinternal "http://documentserver"
    set_plugin_config storageurl "http://webserver"
    set_plugin_config documentserversecret "$DS_JWT_SECRET"
    moodle_php admin/cli/purge_caches.php

    cat <<EOF

Moodle:          http://localhost:$MOODLE_PORT  ($ADMIN_USER / $ADMIN_PASS)
ONLYOFFICE Docs: http://localhost:$DS_PORT
Plugin mounted:  /var/www/html/${MOODLE_MOD_DIR}/onlyofficeeditor
EOF
    if with_assignsubmission; then
        echo "Subplugin:       /var/www/html/${MOODLE_MOD_DIR}/assign/submission/onlyoffice (from $ASSIGNSUBMISSION_DIR)"
    else
        echo "Subplugin:       not mounted, no checkout at '$ASSIGNSUBMISSION_DIR'"
    fi
}

cmd_grunt() {
    detect_layout
    if ! compose run --rm --no-deps -T --entrypoint test node -d /var/www/html/node_modules; then
        log "Installing Moodle's npm dependencies"
        compose run --rm --no-deps -T -w /var/www/html node npm ci
    fi
    local workdir=""
    if [ "${1:-}" = "assign" ]; then
        shift
        if ! with_assignsubmission; then
            echo "No assignsubmission checkout at '$ASSIGNSUBMISSION_DIR'" >&2
            exit 1
        fi
        workdir="/var/www/html/$MOODLE_MOD_DIR/assign/submission/onlyoffice"
    fi
    compose run --rm --no-deps -T ${workdir:+-w "$workdir"} node npx grunt amd "$@"
}

command="${1:-up}"
[ $# -gt 0 ] && shift

case "$command" in
    up)      cmd_up ;;
    down)    compose down ;;
    destroy) compose down --volumes ;;
    grunt)   cmd_grunt "$@" ;;
    upgrade) moodle_php admin/cli/upgrade.php --non-interactive ;;
    php)     moodle_php "$@" ;;
    shell)   compose exec webserver bash ;;
    logs)    compose logs -f "$@" ;;
    *)
        echo "Usage: $0 [up|down|destroy|grunt [assign]|upgrade|php <script> [args]|shell|logs [service]]" >&2
        exit 1
        ;;
esac
